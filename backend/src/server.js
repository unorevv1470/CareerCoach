import 'dotenv/config';
import express from 'express';import cors from 'cors';
import connectDB from './config/db.js';
import authRoutes from './routes/authRoutes.js';import profileRoutes from './routes/profileRoutes.js';import generationRoutes from './routes/generationRoutes.js';import adminRoutes from './routes/adminRoutes.js';
const app=express();
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173'}));app.use(express.json({limit:'1mb'}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'CareerCoach API'}));
app.use('/api/auth',authRoutes);app.use('/api/profile',profileRoutes);app.use('/api/generations',generationRoutes);app.use('/api/admin',adminRoutes);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);res.status(err.name==='ValidationError'?400:500).json({message:err.name==='ValidationError'?err.message:(err.message||'Server error')});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`CareerCoach API running on ${port}`))).catch(err=>{console.error('Database connection failed:',err.message);process.exit(1);});
